import { useState, useEffect } from "react";
import { DeliveryDTO, DeliveryPartnerDTO } from "../../modules/delivery/types/common";
import { ShopDTO } from "../../modules/shop/types/common";

export const useDeliveryPartners = (
  query?: Record<string, any>
): {
  data: { delivery_partners: DeliveryPartnerDTO[] } | null;
  loading: boolean;
} => {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const filterQuery = new URLSearchParams(query).toString();

  useEffect(() => {
    const fetchDeliveryPartners = async () => {
      try {
        const response = await fetch(
          "/admin/delivery_partners" + (query ? `?${filterQuery}` : "")
        );
        const result = await response.json();
        setData(result);
      } catch (error) {
        console.error("Error fetching the data", error);
      } finally {
        setLoading(false);
      }
    };

    fetchDeliveryPartners();
  }, []);

  return { data, loading };
};

