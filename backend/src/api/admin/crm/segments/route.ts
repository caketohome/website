import { MedusaRequest, MedusaResponse } from "@medusajs/framework";
import { CRM_MODULE } from "../../../../modules/crm";

/**
 * GET /admin/crm/segments
 * Admin — List CRM segments.
 */
export async function GET(req: MedusaRequest, res: MedusaResponse) {
  const actorId = (req as any).auth_context?.actor_id as string | undefined;
  if (!actorId) {
    return res.status(401).json({ message: "Unauthorized. Admin credentials required." });
  }

  const crmService = req.scope.resolve(CRM_MODULE) as any;

  try {
    const rawSegments = await crmService.listSegments(req.filterableFields, req.listConfig);
    const segments = rawSegments.map((s: any) => ({
      ...s,
      rules: s.rules ? JSON.parse(s.rules) : [],
      metadata: s.metadata ? JSON.parse(s.metadata) : null,
    }));
    return res.status(200).json({ segments });
  } catch (error: any) {
    const status = error.status || 500;
    return res.status(status).json({ message: error.message, code: error.code });
  }
}

/**
 * POST /admin/crm/segments
 * Admin — Create a new CRM segment.
 */
export async function POST(req: MedusaRequest, res: MedusaResponse) {
  const actorId = (req as any).auth_context?.actor_id as string | undefined;
  if (!actorId) {
    return res.status(401).json({ message: "Unauthorized. Admin credentials required." });
  }

  const crmService = req.scope.resolve(CRM_MODULE) as any;
  const payload = req.body as any;

  try {
    const segment = await crmService.createSegment(payload);
    return res.status(201).json({ segment });
  } catch (error: any) {
    const status = error.status || 500;
    return res.status(status).json({ message: error.message, code: error.code });
  }
}
